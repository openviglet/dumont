@DataJpaTest
@EntityScan(basePackages = "com.viglet.dumont.connector.plugin.aem.persistence.model")
@EnableJpaRepositories(basePackages = "com.viglet.dumont.connector.plugin.aem.persistence.repository")
@Import({ DumAemSourceApi.class, DumAemSourceMapperImpl.class })
@DisplayName("DumAemSourceApi Integration Tests")
class DumAemSourceApiIT {

    private static final String CONTENT_TAGS_CLASS = "com.viglet.dumont.connector.aem.commons.ext.DumAemExtContentTags";
    private static final String CQ_TAGS = "cq:tags";

    @MockitoBean
    private DumAemPluginProcess dumAemPluginProcess;

    @Autowired
    private DumAemSourceApi api;

    @Autowired
    private DumAemSourceRepository sourceRepository;

    @Nested
    @DisplayName("Create (POST) Tests")
    class CreateTests {

        @Test
        @DisplayName("Should persist source with full hierarchy and generate an id")
        void shouldPersistFullHierarchy() {
            DumAemSource saved = api.dumAemSourceAdd(toRequest(newWkndSource()));

            assertNotNull(saved.getId(), "id should be generated by the UUID generator");
            assertEquals("WKND", saved.getName());

            DumAemSource fromDb = sourceRepository.findById(saved.getId()).orElseThrow();
            assertEquals(1, fromDb.getLocalePaths().size());
            assertEquals(1, fromDb.getModels().size());

            DumAemPluginModel model = fromDb.getModels().iterator().next();
            assertEquals(1, model.getTargetAttrs().size());

            DumAemTargetAttribute targetAttr = model.getTargetAttrs().iterator().next();
            assertEquals("tags", targetAttr.getName());
            assertEquals(1, targetAttr.getSourceAttrs().size());

            DumAemSourceAttribute sourceAttr = targetAttr.getSourceAttrs().iterator().next();
            assertEquals(CQ_TAGS, sourceAttr.getName(),
                    "source attr name must be persisted as cq:tags so the tag facet expansion runs");
            assertEquals(CONTENT_TAGS_CLASS, sourceAttr.getClassName());
        }
    }

    @Nested
    @DisplayName("Read (GET) Tests")
    class ReadTests {

        @Test
        @DisplayName("Should list all sources")
        void shouldListAllSources() {
            api.dumAemSourceAdd(toRequest(minimalSource("WKND")));
            api.dumAemSourceAdd(toRequest(minimalSource("OTHER")));

            List<DumAemSource> all = api.dumAemSourceList();

            assertEquals(2, all.size());
        }

        @Test
        @DisplayName("Should return source by id with associated collections")
        void shouldReturnSourceById() {
            DumAemSource saved = api.dumAemSourceAdd(toRequest(newWkndSource()));

            DumAemSource fetched = api.dumAemSourceGet(saved.getId());

            assertEquals(saved.getId(), fetched.getId());
            assertEquals(1, fetched.getLocalePaths().size());
            assertEquals(1, fetched.getModels().size());
        }

        @Test
        @DisplayName("Should return empty source when id does not exist")
        void shouldReturnEmptyWhenNotFound() {
            DumAemSource fetched = api.dumAemSourceGet("does-not-exist");

            assertNotNull(fetched);
            assertNull(fetched.getId());
        }

        @Test
        @DisplayName("Should return a fresh empty structure")
        void shouldReturnFreshStructure() {
            DumAemSource structure = api.dumAemSourceStructure();

            assertNotNull(structure);
            assertNull(structure.getId());
        }
    }

    @Nested
    @DisplayName("Update (PUT) Tests")
    class UpdateTests {

        @Test
        @DisplayName("Should update scalar fields and keep the same id")
        void shouldUpdateScalarFields() {
            DumAemSource saved = api.dumAemSourceAdd(toRequest(newWkndSource()));

            DumAemSource patch = DumAemSource.builder()
                    .name("WKND Updated")
                    .endpoint("http://localhost:9999")
                    .username("admin2")
                    .build();

            ResponseEntity<DumAemSource> response = api.dumAemSourceUpdate(saved.getId(), toRequest(patch));

            assertEquals(HttpStatus.OK, response.getStatusCode());
            DumAemSource body = response.getBody();
            assertNotNull(body);
            assertEquals(saved.getId(), body.getId(), "id must not be changed by update");
            assertEquals("WKND Updated", body.getName());
            assertEquals("http://localhost:9999", body.getEndpoint());
        }

        @Test
        @DisplayName("Should replace models collection respecting orphanRemoval")
        void shouldReplaceModelsCollection() {
            DumAemSource saved = api.dumAemSourceAdd(toRequest(newWkndSource()));

            DumAemSource patch = DumAemSource.builder()
                    .name("WKND")
                    .models(new HashSet<>(List.of(buildModel("cq:Page", "tags", "title", null))))
                    .build();

            ResponseEntity<DumAemSource> response = api.dumAemSourceUpdate(saved.getId(), toRequest(patch));

            assertEquals(HttpStatus.OK, response.getStatusCode());
            DumAemSource fromDb = sourceRepository.findById(saved.getId()).orElseThrow();

            assertEquals(1, fromDb.getModels().size());
            DumAemPluginModel onlyModel = fromDb.getModels().iterator().next();
            List<String> targetNames = onlyModel.getTargetAttrs().stream()
                    .map(DumAemTargetAttribute::getName)
                    .sorted()
                    .toList();
            assertEquals(List.of("tags", "title"), targetNames);
        }

        @Test
        @DisplayName("Should reject update when path id differs from body id")
        void shouldRejectIdMismatch() {
            DumAemSource saved = api.dumAemSourceAdd(toRequest(newWkndSource()));

            DumAemSource patch = DumAemSource.builder()
                    .id("some-other-id")
                    .name("Hacked")
                    .build();

            ResponseEntity<DumAemSource> response = api.dumAemSourceUpdate(saved.getId(), toRequest(patch));

            assertEquals(HttpStatus.BAD_REQUEST, response.getStatusCode());
        }

        @Test
        @DisplayName("Should return 404 when updating a missing source")
        void shouldReturn404WhenSourceMissing() {
            DumAemSource patch = DumAemSource.builder().name("ghost").build();

            ResponseEntity<DumAemSource> response = api.dumAemSourceUpdate("missing-id", toRequest(patch));

            assertEquals(HttpStatus.NOT_FOUND, response.getStatusCode());
        }

        @Test
        @DisplayName("Should preserve cq:tags source-attr name across update cycles")
        void shouldPreserveCqTagsAfterUpdate() {
            DumAemSource saved = api.dumAemSourceAdd(toRequest(newWkndSource()));

            DumAemSource fetched = api.dumAemSourceGet(saved.getId());
            // simulate UI round-trip: read, mutate an unrelated field, send back
            fetched.setName("WKND Renamed");

            ResponseEntity<DumAemSource> response = api.dumAemSourceUpdate(saved.getId(), toRequest(fetched));
            assertEquals(HttpStatus.OK, response.getStatusCode());

            DumAemSource fromDb = sourceRepository.findById(saved.getId()).orElseThrow();
            DumAemTargetAttribute tagsTarget = fromDb.getModels().iterator().next()
                    .getTargetAttrs().iterator().next();
            DumAemSourceAttribute tagsSource = tagsTarget.getSourceAttrs().iterator().next();

            assertEquals(CQ_TAGS, tagsSource.getName(),
                    "round-trip update must not erase the cq:tags name (regression guard)");
            assertEquals(CONTENT_TAGS_CLASS, tagsSource.getClassName());
        }
    }

    @Nested
    @DisplayName("Delete Tests")
    class DeleteTests {

        @Test
        @DisplayName("Should delete source and cascade to children")
        void shouldDeleteWithCascade() {
            DumAemSource saved = api.dumAemSourceAdd(toRequest(newWkndSource()));

            boolean deleted = api.dumAemSourceDelete(saved.getId());

            assertTrue(deleted);
            assertTrue(sourceRepository.findById(saved.getId()).isEmpty());
        }

        @Test
        @DisplayName("Should return false when deleting a missing source")
        void shouldReturnFalseWhenMissing() {
            assertFalse(api.dumAemSourceDelete("missing-id"));
        }
    }

    // ── Fixtures ────────────────────────────────────────────────────────────

    private static DumAemSourceRequest toRequest(DumAemSource source) {
        DumAemSourceRequest request = new DumAemSourceRequest();
        request.setId(source.getId());
        request.setName(source.getName());
        request.setEndpoint(source.getEndpoint());
        request.setUsername(source.getUsername());
        request.setPassword(source.getPassword());
        request.setRootPath(source.getRootPath());
        request.setContentType(source.getContentType());
        request.setSubType(source.getSubType());
        request.setOncePattern(source.getOncePattern());
        request.setDefaultLocale(source.getDefaultLocale());
        request.setLocaleClass(source.getLocaleClass());
        request.setDeltaClass(source.getDeltaClass());
        request.setDependencyClass(source.getDependencyClass());
        request.setAuthor(source.isAuthor());
        request.setPublish(source.isPublish());
        request.setAuthorSNSite(source.getAuthorSNSite());
        request.setPublishSNSite(source.getPublishSNSite());
        request.setAuthorURLPrefix(source.getAuthorURLPrefix());
        request.setPublishURLPrefix(source.getPublishURLPrefix());
        request.setLocalePaths(source.getLocalePaths());
        request.setAttributeSpecifications(source.getAttributeSpecifications());
        request.setModels(source.getModels());
        return request;
    }

    private DumAemSource minimalSource(String name) {
        return DumAemSource.builder()
                .name(name)
                .endpoint("http://localhost:4502")
                .localePaths(new HashSet<>())
                .build();
    }

    private DumAemSource newWkndSource() {
        Set<DumAemSourceLocalePath> localePaths = new HashSet<>();
        localePaths.add(DumAemSourceLocalePath.builder()
                .locale(Locale.US)
                .path("/content/wknd/us/en")
                .build());

        Set<DumAemPluginModel> models = new HashSet<>();
        models.add(buildModel("cq:Page", "tags", null, CONTENT_TAGS_CLASS));

        return DumAemSource.builder()
                .name("WKND")
                .endpoint("http://localhost:4502")
                .username("admin")
                .password("admin")
                .rootPath("/content/wknd")
                .contentType("cq:Page")
                .author(true)
                .publish(true)
                .localePaths(localePaths)
                .models(models)
                .build();
    }

    private DumAemPluginModel buildModel(String type, String firstTargetName, String secondTargetName,
            String tagsClassName) {
        Set<DumAemTargetAttribute> targetAttrs = new HashSet<>();
        targetAttrs.add(buildTargetAttr(firstTargetName,
                Optional.ofNullable(tagsClassName).orElse(CONTENT_TAGS_CLASS)));
        if (secondTargetName != null) {
            targetAttrs.add(buildTargetAttr(secondTargetName, CONTENT_TAGS_CLASS));
        }
        return DumAemPluginModel.builder()
                .type(type)
                .targetAttrs(targetAttrs)
                .build();
    }

    private DumAemTargetAttribute buildTargetAttr(String name, String className) {
        Set<DumAemSourceAttribute> sourceAttrs = new HashSet<>();
        sourceAttrs.add(DumAemSourceAttribute.builder()
                .name(CQ_TAGS)
                .className(className)
                .build());
        return DumAemTargetAttribute.builder()
                .name(name)
                .sourceAttrs(sourceAttrs)
                .build();
    }
}
